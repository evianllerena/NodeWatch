"""Scaffold a new NodeWatch vendor connector from app/integrations/connectors/_template (v0.10.18).

    python tools/new_connector.py cisco_meraki --vendor "Cisco" --product "Meraki Dashboard" --category network_management

Creates:
  app/integrations/connectors/<id>/__init__.py   manifest (+ setup guide stub), connector class
  app/integrations/connectors/<id>/fixtures.py   fixture harness the contract tests use
  app/integrations/connectors/<id>/fixtures/     example recorded answers (replace with real, scrubbed ones)
  tests/test_connector_<id>.py                   runs the connector contract + probe checks for it

and prints the next steps. It never overwrites an existing connector or test file.
"""

from __future__ import annotations

import argparse
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONNECTORS = ROOT / "app" / "integrations" / "connectors"
TEMPLATE = CONNECTORS / "_template"
CATEGORIES = ("network_management", "firewall", "sdwan", "logging", "siem", "other")
ID_RE = re.compile(r"^[a-z][a-z0-9_]{1,40}$")

TEST_FILE = '''"""Contract, setup-guide and probe checks for the {connector_id} connector.

Generated by tools/new_connector.py. The same checks also run for every connector in
tests/test_connectors_contract.py; this file lets you run just yours while you build it:

    pytest -q tests/test_connector_{connector_id}.py
"""

from __future__ import annotations

import pytest

from tests import test_connectors_contract as contract

NAME = "{connector_id}"
CHECKS = (
    "test_manifest_is_valid_and_matches_package",
    "test_claimed_capabilities_are_implemented",
    "test_records_follow_the_domain_contract",
    "test_keys_are_stable_across_calls",
    "test_device_references_resolve",
    "test_no_secret_in_records_or_errors",
    "test_test_connection_is_one_cheap_call",
    "test_connectors_only_read",
    "test_setup_guide_is_complete",
    "test_probe_is_read_only_bounded_and_secret_free",
)


@pytest.mark.parametrize("check", CHECKS)
def test_contract(check):
    getattr(contract, check)(NAME)
'''


def camel(connector_id: str) -> str:
    return "".join(part.capitalize() for part in connector_id.split("_") if part) + "Connector"


def py_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def scaffold(
    connector_id: str,
    *,
    vendor: str,
    product: str,
    category: str,
    connectors_dir: Path = CONNECTORS,
    tests_dir: Path = ROOT / "tests",
) -> dict[str, Path]:
    """Create the package and its test file. Returns the created paths. Raises ValueError on bad input."""
    if not ID_RE.match(connector_id) or connector_id.endswith("_") or "__" in connector_id:
        raise ValueError("connector_id: lower-case letters, digits and single underscores, starting with a letter")
    if category not in CATEGORIES:
        raise ValueError(f"category must be one of {', '.join(CATEGORIES)}")
    if not vendor.strip() or not product.strip():
        raise ValueError("--vendor and --product are required")
    package = Path(connectors_dir) / connector_id
    test_file = Path(tests_dir) / f"test_connector_{connector_id}.py"
    if package.exists() or (CONNECTORS / connector_id).exists():
        raise ValueError(f"a connector named {connector_id} already exists")
    if test_file.exists():
        raise ValueError(f"{test_file} already exists")

    shutil.copytree(TEMPLATE, package, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    cls = camel(connector_id)

    init = package / "__init__.py"
    text = init.read_text(encoding="utf-8")
    text = text.replace(
        '"""TEMPLATE connector — copy this folder to add a vendor. (Ignored by discovery: the name starts with "_".)',
        f'"""{vendor.strip()} {product.strip()} connector — PREVIEW (scaffolded from _template).',
        1,
    )
    text = text.replace(
        'CONNECTOR_ID = "example_vendor"  # ← must equal the folder name', f'CONNECTOR_ID = "{connector_id}"', 1
    )
    text = text.replace('vendor="Example Networks"', f"vendor={py_string(vendor.strip())}", 1)
    text = text.replace('product="Example Controller"', f"product={py_string(product.strip())}", 1)
    text = re.sub(r'category="network_management",[^\n]*', f'category="{category}",', text, count=1)
    text = text.replace("ExampleConnector", cls)
    init.write_text(text, encoding="utf-8")

    fixtures = package / "fixtures.py"
    ftext = fixtures.read_text(encoding="utf-8")
    ftext = ftext.replace(
        "app.integrations.connectors._template import ExampleConnector",
        f"app.integrations.connectors.{connector_id} import {cls}",
    )
    ftext = ftext.replace("ExampleConnector", cls)
    ftext = ftext.replace(
        '"""Fixture harness for the template connector — copy along with the package.',
        f'"""Fixture harness for the {connector_id} connector.',
        1,
    )
    fixtures.write_text(ftext, encoding="utf-8")

    Path(tests_dir).mkdir(parents=True, exist_ok=True)
    test_file.write_text(TEST_FILE.format(connector_id=connector_id), encoding="utf-8")
    return {"package": package, "init": init, "fixtures": fixtures, "test": test_file}


NEXT_STEPS = """
Created {package}
        {test}

Next steps (docs/CONNECTORS.md › "Add a new vendor in 6 steps"):
  1. Manifest + setup guide   {init}
       settings fields, ONLY the capabilities you implement, and SETUP: replace every TODO with the real
       menu paths and the least-privilege role/key (the Add-connection wizard shows it verbatim).
  2. Capabilities             implement each list_* method through self.http() inside self.call(...);
       cite the vendor doc next to every call; delete what you do not support.
  3. Fixtures                 record real answers (scrub names, serials, addresses — example.com,
       RFC 5737 IPs) into {package}/fixtures/ and route them in fixtures.py.
  4. Contract tests           pytest -q {test_rel}
  5. Probe                    the default probe reads each capability once; override probe_plan()
       (see silverpeak_orchestrator/probe.py) for cheaper, explained per-permission checks.
  6. Maturity                 ships as "preview"; promote to "stable" only after it ran on a live system,
       fixtures are real captures and the setup guide has no TODO left.
  7. Allow-list               add the package name to SHIPPED_CONNECTORS in app/integrations/connectors/sdk.py
       (v0.10.22: NodeWatch imports only allow-listed connector packages).
Restart NodeWatch: it appears under Settings › Connections › Add connection.
"""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Scaffold a new NodeWatch vendor connector from _template.")
    parser.add_argument("connector_id", help="folder name and id, e.g. cisco_meraki")
    parser.add_argument("--vendor", required=True, help='e.g. "Cisco"')
    parser.add_argument("--product", required=True, help='e.g. "Meraki Dashboard"')
    parser.add_argument("--category", required=True, choices=CATEGORIES)
    parser.add_argument("--connectors-dir", default=str(CONNECTORS), help=argparse.SUPPRESS)
    parser.add_argument("--tests-dir", default=str(ROOT / "tests"), help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    try:
        paths = scaffold(
            args.connector_id,
            vendor=args.vendor,
            product=args.product,
            category=args.category,
            connectors_dir=Path(args.connectors_dir),
            tests_dir=Path(args.tests_dir),
        )
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    def rel(p: Path) -> str:
        try:
            return str(p.resolve().relative_to(ROOT))
        except ValueError:
            return str(p)

    print(
        NEXT_STEPS.format(
            package=rel(paths["package"]),
            init=rel(paths["init"]),
            test=rel(paths["test"]),
            test_rel=rel(paths["test"]),
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
