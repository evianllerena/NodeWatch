<#
.SYNOPSIS
  Regenerates _internal\requirements.lock and requirements-optional.lock: every package NodeWatch needs on Windows
  (direct and transitive), pinned to an exact version AND SHA-256 hashes, for every
  Python version the launcher accepts (3.10-3.13).

.DESCRIPTION
  The launcher and Build-Bundled-Runtime.ps1 install with `pip --require-hashes`,
  so a package that does not match a recorded hash is refused. Run this on a
  trusted machine with internet access whenever requirements.txt changes, review
  the diff, then run release\generate_integrity.py --update-launcher.

  Only `py.exe` (the Python launcher) and one installed Python are needed: wheels
  for the other versions are downloaded with --python-version, not installed.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File release\Update-Lockfile.ps1
#>
param(
  [string[]]$PythonVersions = @('3.10', '3.11', '3.12', '3.13')
)
$ErrorActionPreference = 'Stop'
$internal = Split-Path -Parent $PSScriptRoot
# v0.10.22: the optional components (SNMP: pysnmp, pyasn1, cryptography + cffi, pycparser) get
# their own hash lock; the launcher no longer installs anything without hashes.
$pairs = @(
  @('requirements.txt', 'requirements.lock'),
  @('requirements-optional.txt', 'requirements-optional.lock')
)
foreach ($pair in $pairs) {
  $requirements = Join-Path $internal $pair[0]
  $lock = Join-Path $internal $pair[1]
  if (-not (Test-Path $requirements)) { continue }
  $work = Join-Path $env:TEMP ("nodewatch-lock-" + [guid]::NewGuid())
  New-Item -ItemType Directory -Path $work | Out-Null

  # name -> pyver -> version ; name|version -> set of hashes
  $versionsByName = @{}
  $hashes = @{}
  try {
    foreach ($pv in $PythonVersions) {
      $dir = Join-Path $work $pv
      New-Item -ItemType Directory -Path $dir | Out-Null
      Write-Host "Resolving win_amd64 / CPython $pv wheels ..."
      py -3 -m pip download --disable-pip-version-check --no-input `
         --only-binary=:all: --platform win_amd64 --python-version $pv `
         --implementation cp -r $requirements -d $dir
      if ($LASTEXITCODE -ne 0) { throw "pip download failed for Python $pv" }
      Get-ChildItem $dir -Filter *.whl | ForEach-Object {
        # Wheel file name: <name>-<version>(-<build>)?-<python>-<abi>-<platform>.whl
        $parts = $_.BaseName -split '-'
        $name = ($parts[0] -replace '_', '-').ToLower()
        $version = $parts[1]
        if (-not $versionsByName.ContainsKey($name)) { $versionsByName[$name] = @{} }
        $versionsByName[$name][$pv] = $version
        $key = "$name|$version"
        if (-not $hashes.ContainsKey($key)) { $hashes[$key] = New-Object System.Collections.Generic.SortedSet[string] }
        [void]$hashes[$key].Add((Get-FileHash $_.FullName -Algorithm SHA256).Hash.ToLower())
      }
    }

    $lines = @(
      '# Generated by release\Update-Lockfile.ps1 - do not edit by hand.',
      "# Target: Windows x64, CPython $($PythonVersions -join ', '). Install with: pip install --require-hashes -r requirements.lock",
      ''
    )
    foreach ($name in ($versionsByName.Keys | Sort-Object)) {
      $perPython = $versionsByName[$name]
      $distinct = @($perPython.Values | Sort-Object -Unique)
      foreach ($version in $distinct) {
        $pythons = @($perPython.Keys | Where-Object { $perPython[$_] -eq $version } | Sort-Object)
        $hashArgs = ($hashes["$name|$version"] | ForEach-Object { "--hash=sha256:$_" }) -join ' '
        if ($pythons.Count -eq $PythonVersions.Count) {
          $lines += "$name==$version $hashArgs"
        } else {
          # Different versions per Python (or package only needed on some): use markers.
          $marker = ($pythons | ForEach-Object { "python_version == `"$_`"" }) -join ' or '
          $lines += "$name==$version ; $marker $hashArgs"
        }
      }
    }
    $lines | Set-Content -Path $lock -Encoding ascii
    Write-Host "Wrote $lock"
    Get-Content $lock
  }
  finally {
    Remove-Item $work -Recurse -Force -ErrorAction SilentlyContinue
  }
}
