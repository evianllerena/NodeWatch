def _condition(
    *,
    severity,
    type,
    group,
    title,
    device,
    device_type,
    mac,
    site,
    site_id,
    detail,
    age,
    source,
    timestamp,
    alarm_id="",
    acked=False,
    details=None,
):
    key = f"alarm:{alarm_id}" if alarm_id else f"event:{type}|{device}|{site}|{timestamp}"
    return {
        "severity": severity,
        "type": type,
        "group": group,
        "title": title,
        "device": device,
        "device_type": device_type,
        "mac": mac,
        "site": site,
        "site_id": site_id,
        "detail": detail,
        "age": age,
        "source": source,
        "timestamp": timestamp,
        "alarm_id": alarm_id,
        "acked": acked,
        "details": details or {},
        "dismiss_key": key,
    }


