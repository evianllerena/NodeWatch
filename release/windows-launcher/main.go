type hashResult struct {
	rel string
	sum string
	err error
}

// hashManifestFiles hashes every listed file, several at a time (v0.10.23), in sorted order.
func hashManifestFiles(root string, files map[string]string, clean func(string) (string, bool)) ([]hashResult, error) {
	rels := make([]string, 0, len(files))
	for rel := range files {
		if _, ok := clean(rel); !ok {
			return nil, fmt.Errorf("unsafe integrity path: %s", rel)
		}
		rels = append(rels, rel)
	}
	sort.Strings(rels)
	results := make([]hashResult, len(rels))
	workers := runtime.NumCPU() * 2
	if workers < 4 {
		workers = 4
	}
	if workers > 16 {
		workers = 16
	}
	jobs := make(chan int)
	var wg sync.WaitGroup
	for w := 0; w < workers; w++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for i := range jobs {
				path, _ := clean(rels[i])
				sum, err := hashFile(filepath.Join(root, path))
				results[i] = hashResult{rels[i], sum, err}
			}
		}()
	}
	for i := range rels {
		jobs <- i
	}
	close(jobs)
	wg.Wait()
	return results, nil
}

// readAppPath returns the program registered under App Paths\<exe> in root ("" if none).
func readAppPath(root syscall.Handle, exe string) string {
	name, _ := syscall.UTF16PtrFromString(`SOFTWARE\Microsoft\Windows\CurrentVersion\App Paths\` + exe)
	var key syscall.Handle
	if syscall.RegOpenKeyEx(root, name, 0, syscall.KEY_READ, &key) != nil {
		return ""
	}
	defer syscall.RegCloseKey(key)
	value, _ := syscall.UTF16PtrFromString("")
	var buf [1024]uint16
	n := uint32(len(buf) * 2)
	var typ uint32
	if syscall.RegQueryValueEx(key, value, nil, &typ, (*byte)(unsafe.Pointer(&buf[0])), &n) != nil {
		return ""
	}
	if typ != syscall.REG_SZ && typ != syscall.REG_EXPAND_SZ {
		return ""
	}
	return strings.Trim(syscall.UTF16ToString(buf[:]), `"`)
}

// findAppBrowser finds the program the app window opens with. The first name is the App Paths entry
// NodeWatch registers for its own window (app/core/app_window.py, v0.10.39). The shipped v0.10.42 launcher
// has this name in its data while its Program Files fallback still compares with "msedge.exe"; this source
// reproduces that exactly.
func findAppBrowser() string {
	for _, exe := range []string{"nwhost.exe", "chrome.exe"} {
		for _, root := range []syscall.Handle{syscall.HKEY_CURRENT_USER, syscall.HKEY_LOCAL_MACHINE} {
			if p := readAppPath(root, exe); p != "" && fileExists(p) {
				return p
			}
		}
		var bases []string
		for _, v := range []string{"ProgramFiles(x86)", "ProgramFiles", "LOCALAPPDATA"} {
			if d := os.Getenv(v); d != "" {
				bases = append(bases, d)
			}
		}
		for _, base := range bases {
			var p string
			if exe == "msedge.exe" {
				p = filepath.Join(base, "Microsoft", "Edge", "Application", exe)
			} else {
				p = filepath.Join(base, "Google", "Chrome", "Application", exe)
			}
			if fileExists(p) {
				return p
			}
		}
	}
	return ""
}

// openApp opens the page in NodeWatch's app window (v0.10.39), else in the default browser.
func (l *launcher) openApp(url string) {
	if os.Getenv("NODEWATCH_OPEN_IN_BROWSER") == "1" {
		l.logf("opening %s in the default browser (NODEWATCH_OPEN_IN_BROWSER=1)", url)
		openBrowser(url)
		return
	}
	exe := findAppBrowser()
	if exe == "" {
		l.logf("Edge/Chrome not found; opening %s in the default browser", url)
		openBrowser(url)
		return
	}
	profile := filepath.Join(l.dataRoot, "app-window")
	_ = os.MkdirAll(profile, 0700)
	err := exec.Command(exe, "--app="+url, "--user-data-dir="+profile, "--no-first-run", "--no-default-browser-check", "--disable-extensions", "--window-size=1440,900").Start()
	if err != nil {
		l.logf("app window could not start with %s (%v); opening the default browser", exe, err)
		openBrowser(url)
		return
	}
	l.logf("opened NodeWatch app window with %s", exe)
}

