func startSplash(path string) func() {
	done := make(chan struct{})
	finished := make(chan struct{})
	go func() {
		runtime.LockOSThread()
		defer runtime.UnlockOSThread()
		defer close(finished)
		p, _ := syscall.UTF16PtrFromString(path)
		hbmp, _, _ := procLoadImageW.Call(0, uintptr(unsafe.Pointer(p)), 0, 0, 0, 0x0010)
		if hbmp == 0 {
			<-done
			return
		}
		class, _ := syscall.UTF16PtrFromString("STATIC")
		wpx, hpx := bmpDimensions(path)
		if wpx <= 0 || hpx <= 0 {
			wpx, hpx = 420, 420
		}
		hwnd, _, _ := procCreateWindowExW.Call(0, uintptr(unsafe.Pointer(class)), 0, 0x80000000|0x0000000E, 0, 0, uintptr(wpx), uintptr(hpx), 0, 0, 0, 0)
		if hwnd == 0 {
			<-done
			return
		}
		procSendMessageW.Call(hwnd, 0x0172, 0, hbmp) // STM_SETIMAGE / IMAGE_BITMAP
		sw, _, _ := procGetSystemMetrics.Call(0)
		sh, _, _ := procGetSystemMetrics.Call(1)
		w, h := uintptr(wpx), uintptr(hpx)
		x, y := uintptr(0), uintptr(0)
		if sw > w {
			x = (sw - w) / 2
		}
		if sh > h {
			y = (sh - h) / 2
		}
		procSetWindowPos.Call(hwnd, 0, x, y, w, h, 0x0040)
		procShowWindow.Call(hwnd, 5)
		procUpdateWindow.Call(hwnd)
		<-done
		procDestroyWindow.Call(hwnd)
	}()
	once := make(chan struct{}, 1)
	return func() {
		select {
		case once <- struct{}{}:
			close(done)
			select {
			case <-finished:
			case <-time.After(500 * time.Millisecond):
			}
		default:
		}
	}
}

func bmpDimensions(path string) (int, int) {
	f, err := os.Open(path)
	if err != nil {
		return 0, 0
	}
	defer f.Close()
	header := make([]byte, 26)
	if _, err := io.ReadFull(f, header); err != nil || string(header[:2]) != "BM" {
		return 0, 0
	}
	w := int(int32(binary.LittleEndian.Uint32(header[18:22])))
	h := int(int32(binary.LittleEndian.Uint32(header[22:26])))
	if h < 0 {
		h = -h
	}
	return w, h
}

