// installFolderProblems names the broad principals that can change the install folder (each once).
// NODEWATCH_ALLOW_SHARED_INSTALL=1 starts anyway (logged), for lab PCs with one user.
func (l *launcher) installFolderProblems() []string {
	var problems []string
	seen := map[string]bool{}
	for _, dir := range []string{l.exeDir, l.internalDir} {
		found, err := writableByOthers(dir)
		if err != nil {
			l.logf("install folder permission check skipped for %s: %v", dir, err)
			continue
		}
		for _, f := range found {
			sid := strings.SplitN(f, " ", 2)[0]
			l.logf("install folder %s: %s can write", dir, f)
			if name := principalName(sid); !seen[name] {
				seen[name] = true
				problems = append(problems, name)
			}
		}
	}
	if len(problems) > 0 && os.Getenv("NODEWATCH_ALLOW_SHARED_INSTALL") == "1" {
		l.logf("WARNING: starting from a folder other users can change because NODEWATCH_ALLOW_SHARED_INSTALL=1")
		return nil
	}
	return problems
}

