func main() {
	// Resolve every DLL loaded by name (including ones Windows loads on our behalf, such as
	// ntmarta.dll during the folder permission check) from System32 only, never from the
	// folder NodeWatch.exe was started from (v0.10.22).
	const loadLibrarySearchSystem32 = 0x00000800
	_, _, _ = procSetDefaultDllDirectories.Call(loadLibrarySearchSystem32)
	runtime.LockOSThread()
	l, err := newLauncher()
	if err != nil {
		messageBox("NodeWatch", err.Error())
		return
	}

	// Stop only older NodeWatch-owned Python runtimes. This prevents upgrades
	// from leaving every historical backend resident and frees legacy files for
	// the one-time profile rename.
	l.stopStaleBackends()
	l.migrateLegacyProfile()
	// Keep Python's bytecode cache in the private data folder for every child
	// process: a .pyc planted in an application __pycache__ folder is then never
	// read, and the bundled runtime folder stays exactly as the manifest lists it.
	// Shared across versions: Python re-checks each .pyc against its source (mtime and size), so an
	// upgrade only recompiles the modules that changed instead of every module.
	_ = os.Setenv("PYTHONPYCACHEPREFIX", filepath.Join(l.dataRoot, "pycache", "shared"))
	if err := l.initLog(); err != nil {
		messageBox("NodeWatch", "Unable to initialize the NodeWatch log folder.\n\n"+err.Error())
		return
	}
	l.logf("launching NodeWatch v%s build=%s publisher=%s", appVersion, appBuild, publisher)

	if err := l.verifyIntegrity(); err != nil {
		l.logf("integrity validation failed: %v", err)
		messageBox("NodeWatch", "NodeWatch application files failed integrity validation.\n\n"+err.Error()+"\n\nRe-extract a clean release package.")
		return
	}
	l.logf("runtime integrity validation passed")

	// v0.10.22: never run from a folder other users can change; offer the one-click install instead.
	if problems := l.installFolderProblems(); len(problems) > 0 {
		l.logf("install folder is writable by other users: %s", strings.Join(problems, ", "))
		l.offerProfileInstall(problems)
		return
	}

	if port, ok := l.findExistingExactBackend(); ok {
		l.logf("opened existing exact backend on port %d", port)
		l.openApp(fmt.Sprintf("http://127.0.0.1:%d/", port))
		return
	}

	closeSplash := startSplash(filepath.Join(l.internalDir, "branding", "startup.bmp"))
	defer closeSplash()

	py, err := l.ensurePrivateRuntime()
	if err != nil {
		l.logf("runtime preparation failed: %v", err)
		messageBox("NodeWatch", "NodeWatch could not prepare its private Python runtime.\n\n"+err.Error()+"\n\nSee:\n"+l.logPath)
		return
	}

	// Preferred: NodeWatchBackend.exe hosting the bundled interpreter. Always last:
	// the private runtime's python.exe (the pre-v0.10.12 behaviour).
	attempts := l.backendAttempts(py)
	var (
		port    int
		status  backendStatus
		started bool
		hostErr error
	)
	for i, a := range attempts {
		last := i == len(attempts)-1
		nonce, err := makeNonce()
		if err != nil {
			l.logf("nonce generation failed: %v", err)
			messageBox("NodeWatch", "Unable to create a secure launcher handshake.\n\nSee:\n"+l.logPath)
			return
		}
		cmd, exited, err := l.startBackend(a, nonce, i == 0)
		if err != nil {
			l.logf("backend start failed (%s): %v", a.label, err)
			if a.isHost {
				hostErr = err
			}
			continue
		}
		l.logf("started candidate backend (%s) pid=%d", a.label, cmd.Process.Pid)
		timeout := startupTimeout
		if !last && a.timeout > 0 {
			timeout = a.timeout
		}
		port, status, err = l.waitForBackend(nonce, a.exe, exited, timeout)
		if err == nil {
			started = true
			break
		}
		l.logf("backend verification failed (%s): %v", a.label, err)
		if cmd.Process != nil {
			_ = cmd.Process.Kill()
		}
		if a.isHost {
			hostErr = err
		}
		if !last {
			l.logf("falling back to %s", attempts[i+1].label)
		}
	}
	if started && hostErr != nil {
		// Only the host failed: remember it so later starts skip the host delay.
		l.disableHost(hostErr)
	}
	if !started {
		messageBox("NodeWatch", "NodeWatch backend startup failed before secure verification completed.\n\nSee both logs:\n"+l.logPath+"\n"+filepath.Join(l.dataRoot, "logs", "backend-launcher.log"))
		return
	}
	l.logf("verified backend v%s build=%s pid=%d on port %d with launcher handshake", status.Version, status.Build, status.PID, port)

	closeSplash()
	l.openApp(fmt.Sprintf("http://127.0.0.1:%d/", port))
}

func newLauncher() (*launcher, error) {
	exe, err := os.Executable()
	if err != nil {
		return nil, err
	}
	exeDir := filepath.Dir(exe)
	internal := filepath.Join(exeDir, "_internal")
	if st, err := os.Stat(internal); err != nil || !st.IsDir() {
		return nil, errors.New("_internal application folder is missing")
	}
	local := os.Getenv("LOCALAPPDATA")
	if strings.TrimSpace(local) == "" {
		return nil, errors.New("LOCALAPPDATA is not available")
	}
	data := filepath.Join(local, "NodeWatch")
	return &launcher{exeDir: exeDir, internalDir: internal, dataRoot: data, logPath: filepath.Join(data, "logs", "native-launcher.log")}, nil
}

func (l *launcher) initLog() error {
	return os.MkdirAll(filepath.Dir(l.logPath), 0700)
}

func (l *launcher) logf(format string, args ...any) {
	_ = os.MkdirAll(filepath.Dir(l.logPath), 0700)
	f, err := os.OpenFile(l.logPath, os.O_CREATE|os.O_APPEND|os.O_WRONLY, 0600)
	if err != nil {
		return
	}
	defer f.Close()
	ts := time.Now().Format(time.RFC3339)
	_, _ = fmt.Fprintf(f, "%s %s\n", ts, fmt.Sprintf(format, args...))
}

func (l *launcher) migrateLegacyProfile() {
	legacy := filepath.Join(filepath.Dir(l.dataRoot), "MistNetworkTools")
	if _, err := os.Stat(legacy); err != nil {
		return
	}

	if _, err := os.Stat(l.dataRoot); os.IsNotExist(err) {
		if err := os.Rename(legacy, l.dataRoot); err == nil {
			l.logf("migrated legacy application data to NodeWatch by atomic rename")
			return
		}
	}

	_ = os.MkdirAll(l.dataRoot, 0700)
	backupRoot := filepath.Join(l.dataRoot, "migration-backup", "MistNetworkTools-v0.8.9")
	copied, identical, conflicts := 0, 0, 0
	hadError := false
	_ = filepath.Walk(legacy, func(path string, info os.FileInfo, walkErr error) error {
		if walkErr != nil {
			hadError = true
			return nil
		}
		rel, err := filepath.Rel(legacy, path)
		if err != nil || rel == "." {
			return nil
		}
		dst := filepath.Join(l.dataRoot, rel)
		if info.IsDir() {
			_ = os.MkdirAll(dst, 0700)
			return nil
		}
		if !info.Mode().IsRegular() {
			return nil
		}
		if _, err := os.Stat(dst); os.IsNotExist(err) {
			if err := copyVerified(path, dst); err != nil {
				hadError = true
			} else {
				copied++
			}
			return nil
		}
		same, err := sameFile(path, dst)
		if err == nil && same {
			identical++
			return nil
		}
		conflict := filepath.Join(backupRoot, rel)
		if err := copyVerified(path, conflict); err != nil {
			hadError = true
		} else {
			conflicts++
		}
		return nil
	})
	if !hadError {
		if err := os.RemoveAll(legacy); err != nil {
			hadError = true
		}
	}
	l.logf("legacy profile merge completed copied=%d identical=%d conflicts_preserved=%d cleanup_pending=%t", copied, identical, conflicts, hadError)
}

func copyVerified(src, dst string) error {
	if err := os.MkdirAll(filepath.Dir(dst), 0700); err != nil {
		return err
	}
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()
	out, err := os.OpenFile(dst, os.O_CREATE|os.O_TRUNC|os.O_WRONLY, 0600)
	if err != nil {
		return err
	}
	if _, err = io.Copy(out, in); err != nil {
		out.Close()
		return err
	}
	if err = out.Close(); err != nil {
		return err
	}
	same, err := sameFile(src, dst)
	if err != nil {
		return err
	}
	if !same {
		return errors.New("copy verification failed")
	}
	return nil
}

func sameFile(a, b string) (bool, error) {
	ha, err := hashFile(a)
	if err != nil {
		return false, err
	}
	hb, err := hashFile(b)
	if err != nil {
		return false, err
	}
	return ha == hb, nil
}

func hashFile(path string) (string, error) {
	f, err := os.Open(path)
	if err != nil {
		return "", err
	}
	defer f.Close()
	h := sha256.New()
	if _, err := io.Copy(h, f); err != nil {
		return "", err
	}
	return hex.EncodeToString(h.Sum(nil)), nil
}

func (l *launcher) verifyIntegrity() error {
	manifestPath := filepath.Join(l.internalDir, "integrity.json")
	actualManifestHash, err := hashFile(manifestPath)
	if err != nil {
		return fmt.Errorf("cannot read integrity manifest: %w", err)
	}
	if !strings.EqualFold(actualManifestHash, manifestSHA256) {
		return errors.New("integrity manifest digest does not match this NodeWatch launcher")
	}
	raw, err := os.ReadFile(manifestPath)
	if err != nil {
		return err
	}
	var m manifest
	if err := json.Unmarshal(raw, &m); err != nil {
		return fmt.Errorf("invalid integrity manifest: %w", err)
	}
	if m.Build != appBuild {
		return fmt.Errorf("integrity manifest build mismatch: %s", m.Build)
	}
	l.manifest = m
	results, err := hashManifestFiles(l.internalDir, m.Files, func(rel string) (string, bool) {
		clean := filepath.Clean(filepath.FromSlash(rel))
		if filepath.IsAbs(clean) || strings.HasPrefix(clean, ".."+string(os.PathSeparator)) || clean == ".." {
			return "", false
		}
		return clean, true
	})
	if err != nil {
		return err
	}
	for _, r := range results {
		rel, actual, err := r.rel, r.sum, r.err
		if err != nil && errors.Is(err, fs.ErrNotExist) && rel == bundledRuntime && l.bundledPython() != "" {
			// The v0.10.12 backend host is optional (e.g. removed by antivirus):
			// a missing file cannot run, and the backend then starts as python.exe.
			l.logf("backend host %s is missing; the backend will run as python.exe", rel)
			continue
		}
		if err != nil {
			return fmt.Errorf("integrity file %s: %w", rel, err)
		}
		if !strings.EqualFold(actual, m.Files[rel]) {
			return fmt.Errorf("modified application file: %s", rel)
		}
	}
	// A bundled runtime is executed directly, so it must be covered by the manifest.
	if fileExists(filepath.Join(l.internalDir, filepath.FromSlash(bundledRuntime))) {
		if _, listed := m.Files[bundledRuntime]; !listed {
			return fmt.Errorf("bundled runtime %s is not listed in the integrity manifest", bundledRuntime)
		}
	}
	return l.rejectUnlistedCode(m)
}

// quarantineUnlistedCode moves files that are not in the manifest out of the places the
// backend loads code or pages from (code at the _internal top level; anything under app/
// and runtime/) into
// %LOCALAPPDATA%\NodeWatch\quarantine\<timestamp>\. Python searches the working
// directory first, so a planted _internal\uvicorn.py, a stray sourceless .pyc, or a
// DLL next to NodeWatchBackend.exe would otherwise run inside NodeWatch.
//
// Moving (instead of refusing to start) keeps the usual upgrade method working:
// extracting a new release over the old folder leaves files the new release no
// longer has; they are set aside and logged, never executed. Startup is refused
// only if a file cannot be moved.
func (l *launcher) rejectUnlistedCode(m manifest) error {
	isCode := func(name string) bool {
		ext := strings.ToLower(filepath.Ext(name))
		return ext == ".py" || ext == ".pyc" || ext == ".pyd" || ext == ".pth" || ext == ".dll"
	}
	listed := func(abs string) bool {
		rel, err := filepath.Rel(l.internalDir, abs)
		if err != nil {
			return false
		}
		_, ok := m.Files[filepath.ToSlash(rel)]
		return ok
	}
	var unlisted []string
	entries, err := os.ReadDir(l.internalDir)
	if err != nil {
		return err
	}
	for _, e := range entries {
		if !e.IsDir() && isCode(e.Name()) && !listed(filepath.Join(l.internalDir, e.Name())) {
			unlisted = append(unlisted, filepath.Join(l.internalDir, e.Name()))
		}
	}
	// Every file of the bundled runtime must be listed, code or not.
	runtimeDir := filepath.Join(l.internalDir, "runtime")
	if st, err := os.Stat(runtimeDir); err == nil && st.IsDir() {
		err := filepath.WalkDir(runtimeDir, func(path string, d fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if !d.IsDir() && !listed(path) {
				unlisted = append(unlisted, path)
			}
			return nil
		})
		if err != nil {
			return err
		}
	}
	appDir := filepath.Join(l.internalDir, "app")
	err = filepath.WalkDir(appDir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if d.Name() == "__pycache__" {
				return filepath.SkipDir // never read: PYTHONPYCACHEPREFIX points Python at the data folder
			}
			return nil
		}
		// v0.10.22: every unlisted file under app/ is set aside, not only Python code. An
		// unlisted .js/.html/.svg under app/static would otherwise be served same-origin
		// (CSP 'self'), where it can read the request token from the page.
		if !listed(path) {
			unlisted = append(unlisted, path)
		}
		return nil
	})
	if err != nil {
		return err
	}
	if len(unlisted) == 0 {
		return nil
	}
	quarantine := filepath.Join(l.dataRoot, "quarantine", time.Now().UTC().Format("20060102T150405Z"))
	for _, path := range unlisted {
		rel, _ := filepath.Rel(l.internalDir, path)
		dst := filepath.Join(quarantine, rel)
		if err := os.MkdirAll(filepath.Dir(dst), 0700); err == nil {
			err = os.Rename(path, dst)
			if err != nil { // different volume: copy then delete
				if cerr := copyVerified(path, dst); cerr == nil {
					err = os.Remove(path)
				}
			}
			if err == nil {
				l.logf("moved unlisted file %s to %s (not part of v%s)", filepath.ToSlash(rel), dst, appVersion)
				continue
			}
		}
		return fmt.Errorf("unexpected file %s is not part of this release and could not be moved aside; delete it or re-extract into an empty folder", filepath.ToSlash(rel))
	}
	return nil
}

func (l *launcher) ensurePrivateRuntime() (string, error) {
	// Release packages may ship a self-contained Windows backend runtime (the
	// legacy embeddable layout from Build-Bundled-Runtime.ps1). When present, use
	// it directly so a fresh PC does not need Python installed. In the v0.10.12
	// layout (runtime\python\) the same file name is the backend host instead,
	// which has no packages of its own, so it is not tried here.
	bundled := filepath.Join(l.internalDir, "runtime", "NodeWatchBackend.exe")
	if fileExists(bundled) && l.bundledPython() == "" {
		if err := verifyRuntimeLogged(bundled, filepath.Join(l.dataRoot, "logs", "runtime-bootstrap.log")); err == nil {
			l.logf("using bundled NodeWatch backend runtime: %s", bundled)
			return bundled, nil
		}
	}
	// Bundled packages (runtime\site-packages, listed in the manifest): run the bundled interpreter with them
	// directly. Nothing is downloaded or installed.
	if site := l.bundledSite(); site != "" {
		py := l.bundledPython()
		env := bundledEnv(site, l.internalDir)
		if err := verifyRuntimeEnv(py, env, filepath.Join(l.dataRoot, "logs", "runtime-bootstrap.log")); err != nil {
			return "", fmt.Errorf("the bundled Python packages failed their self-test (%v); re-extract a complete release package", err)
		}
		l.site = site
		l.logf("using bundled interpreter and bundled packages (no download): %s", site)
		return py, nil
	}
	// The runtime is located further down, once the requirements hash is known.
	var runtimeDir, py string
	// With requirements.lock present (and listed in the manifest) dependencies are
	// installed only with matching SHA-256 hashes, so a substituted package on PyPI
	// is refused. Deleting the lock from such a release fails integrity validation.
	req := filepath.Join(l.internalDir, lockFileName)
	hashPinned := true
	if !fileExists(req) {
		// v0.10.22: fail closed. Installing without hashes lets a substituted package (or a
		// pip.ini planted by another user) run inside the process that holds the Mist write
		// token. Only a development build linked with
		//   -ldflags "-X main.allowUnhashedInstall=true"
		// may still fall back to the version-pinned requirements.txt.
		if allowUnhashedInstall != "true" {
			return "", errors.New(lockFileName + " is missing from this release, so dependencies cannot be installed with hash verification. Re-extract a complete release package (release builders: run release\\Update-Lockfile.ps1, then release\\generate_integrity.py --update-launcher).")
		}
		hashPinned = false
		req = filepath.Join(l.internalDir, "requirements.txt")
		l.logf("WARNING: development build: %s not found; installing version-pinned requirements.txt WITHOUT hash verification", lockFileName)
	} else if _, listed := l.manifest.Files[lockFileName]; !listed {
		return "", errors.New(lockFileName + " is not covered by the integrity manifest. Re-run release\\generate_integrity.py after updating the lock file.")
	}
	reqHash, err := hashFile(req)
	if err != nil {
		return "", err
	}
	// Keyed by the pinned dependencies and the bundled interpreter (its hash and folder), not by
	// the NodeWatch version: an upgrade that keeps the same dependencies reuses the private
	// runtime instead of re-downloading every package from PyPI (the slowest part of a first start).
	keySource := reqHash
	// Optional components install from their own hash lock (v0.10.22). Without it they are
	// skipped (SNMP then reports "component missing") unless this is a development build.
	optReq := filepath.Join(l.internalDir, optionalLockName)
	optHash := ""
	if fileExists(optReq) {
		if _, listed := l.manifest.Files[optionalLockName]; !listed {
			return "", errors.New(optionalLockName + " is not covered by the integrity manifest. Re-run release\\generate_integrity.py.")
		}
	} else if allowUnhashedInstall == "true" && fileExists(filepath.Join(l.internalDir, optionalReqName)) {
		optReq = filepath.Join(l.internalDir, optionalReqName)
		if _, listed := l.manifest.Files[optionalReqName]; !listed {
			return "", errors.New(optionalReqName + " is not covered by the integrity manifest. Re-run release\\generate_integrity.py.")
		}
	} else {
		optReq = ""
		if fileExists(filepath.Join(l.internalDir, optionalReqName)) {
			l.logf("WARNING: %s not found; optional components (SNMP) are not installed because they cannot be hash-verified", optionalLockName)
		}
	}
	if optReq != "" {
		if optHash, err = hashFile(optReq); err != nil {
			return "", err
		}
	}
	if b := l.bundledPython(); b != "" {
		keySource += "|" + l.manifest.Files[bundledPythonDir+"/python.exe"] + "|" + strings.ToLower(filepath.Clean(b))
	}
	keySum := sha256.Sum256([]byte(keySource))
	runtimeDir = filepath.Join(l.dataRoot, "runtime", "deps-"+hex.EncodeToString(keySum[:])[:16])
	py = filepath.Join(runtimeDir, "Scripts", "python.exe")
	marker := filepath.Join(runtimeDir, ".nodewatch-runtime")

	if markerBytes, err := os.ReadFile(marker); err == nil {
		lines := strings.Split(strings.TrimSpace(string(markerBytes)), "\n")
		if len(lines) > 0 && strings.TrimSpace(lines[0]) == reqHash && fileExists(py) {
			if err := verifyRuntime(py); err == nil {
				l.logf("reusing verified private runtime: %s", py)
				if optHash != "" && !(len(lines) > 1 && strings.TrimSpace(lines[1]) == "optional:"+optHash) {
					// Optional features were not installed last time (e.g. offline): try again, never fatal.
					l.installOptional(py, optReq, optHash, marker, reqHash)
				}
				now := time.Now()
				_ = os.Chtimes(marker, now, now) // "last used", so other installs never prune it
				l.pruneOldRuntimes(runtimeDir)
				return py, nil
			}
		}
	}

	_ = os.RemoveAll(runtimeDir)
	bundledPy := l.bundledPython()
	candidate, err := findPython(bundledPy)
	if err != nil {
		return "", err
	}
	err = l.buildPrivateRuntime(candidate, runtimeDir, py, req, hashPinned)
	if err != nil && bundledPy != "" && samePath(candidate.Exe, bundledPy) {
		// The bundled interpreter is new in v0.10.12: if anything about it fails
		// on this PC, fall back to an installed Python exactly as before.
		l.logf("private runtime from the bundled interpreter failed: %v; retrying with an installed Python", err)
		_ = os.RemoveAll(runtimeDir)
		if installed, findErr := findPython(""); findErr == nil {
			candidate = installed
			err = l.buildPrivateRuntime(candidate, runtimeDir, py, req, hashPinned)
		} else {
			l.logf("no installed Python available for the fallback: %v", findErr)
		}
	}
	if err != nil {
		return "", err
	}
	if err := os.WriteFile(marker, []byte(reqHash+"\n"), 0600); err != nil {
		return "", err
	}
	if optHash != "" {
		l.installOptional(py, optReq, optHash, marker, reqHash)
	}
	l.logf("private runtime ready: %s (base interpreter %s)", py, candidate.Exe)
	l.pruneOldRuntimes(runtimeDir)
	return py, nil
}

// pruneOldRuntimes removes private runtimes other than keep that have not been used for
// runtimePruneAge. It only runs after the current runtime is ready (never on a failed or offline
// build, so the last working runtime survives for a rollback). A runtime another install still uses
// is touched on every start of that install and is therefore never old enough to be removed.
const runtimePruneAge = 14 * 24 * time.Hour

func (l *launcher) pruneOldRuntimes(keep string) {
	root := filepath.Join(l.dataRoot, "runtime")
	entries, err := os.ReadDir(root)
	if err != nil {
		return
	}
	for _, e := range entries {
		dir := filepath.Join(root, e.Name())
		if !e.IsDir() || samePath(dir, keep) {
			continue
		}
		if !strings.HasPrefix(e.Name(), "v") && !strings.HasPrefix(e.Name(), "deps-") {
			continue
		}
		used := dir
		if fileExists(filepath.Join(dir, ".nodewatch-runtime")) {
			used = filepath.Join(dir, ".nodewatch-runtime")
		}
		st, err := os.Stat(used)
		if err != nil || time.Since(st.ModTime()) < runtimePruneAge {
			continue
		}
		if err := os.RemoveAll(dir); err == nil {
			l.logf("removed private runtime unused for %d days: %s", int(time.Since(st.ModTime()).Hours()/24), dir)
		} else {
			l.logf("could not remove old private runtime %s: %v", dir, err)
		}
	}
}

// buildPrivateRuntime creates the venv from candidate and installs the pinned requirements.
func (l *launcher) buildPrivateRuntime(candidate pythonCandidate, runtimeDir, py, req string, hashPinned bool) error {
	l.logf("creating private runtime using %s", candidate.Exe)
	args := append([]string{}, candidate.Prefix...)
	args = append(args, "-m", "venv", runtimeDir)
	if err := runHidden(candidate.Exe, args, l.internalDir, nil, filepath.Join(l.dataRoot, "logs", "runtime-bootstrap.log")); err != nil {
		return fmt.Errorf("private runtime creation failed: %w", err)
	}
	if !fileExists(py) {
		return errors.New("private runtime did not create Scripts\\python.exe")
	}
	if hashPinned {
		l.logf("installing hash-pinned wheel-only Python requirements from %s", lockFileName)
	} else {
		l.logf("installing version-pinned wheel-only Python requirements from requirements.txt (no hash verification)")
	}
	if err := l.pipInstall(py, req, hashPinned); err != nil {
		return fmt.Errorf("pinned dependency installation failed: %w", err)
	}
	return verifyRuntimeLogged(py, filepath.Join(l.dataRoot, "logs", "runtime-bootstrap.log"))
}

// pipInstall installs a requirements file wheel-only. When the package ships an offline wheel
// folder (runtime\wheels, built by release\Build-Offline-Wheels.ps1) it installs from there
// without contacting PyPI; if that fails (a wheel missing) it falls back to PyPI, which honours
// the Windows/system proxy and HTTPS_PROXY like other Python tools.
func (l *launcher) pipInstall(py, req string, hashPinned bool) error {
	// Every install is --require-hashes (v0.10.22), so a redirected index or a planted
	// C:\ProgramData\pip\pip.ini can no longer substitute a package; pip's own configuration
	// (corporate mirrors, proxies) is therefore honoured as before. Only PYTHON* variables, which
	// can inject code into pip itself, are removed (see pipEnvironment).
	base := []string{"-m", "pip", "install", "--disable-pip-version-check", "--no-input", "--no-cache-dir", "--only-binary=:all:"}
	if hashPinned {
		base = append(base, "--require-hashes")
	}
	env := pipEnvironment()
	logPath := filepath.Join(l.dataRoot, "logs", "runtime-bootstrap.log")
	wheels := filepath.Join(l.internalDir, filepath.FromSlash(wheelsDirName))
	if matches, _ := filepath.Glob(filepath.Join(wheels, "*.whl")); len(matches) > 0 {
		args := append(append([]string{}, base...), "--no-index", "--find-links", wheels, "-r", req)
		if err := runHidden(py, args, l.internalDir, env, logPath); err == nil {
			l.logf("installed %s from the bundled offline wheels (no internet needed)", filepath.Base(req))
			return nil
		} else {
			l.logf("offline wheel install of %s failed (%v); trying PyPI", filepath.Base(req), err)
		}
	}
	// Bounded so a network that silently drops traffic cannot stall start-up for minutes.
	args := append(append([]string{}, base...), "--timeout", "10", "--retries", "1", "-r", req)
	return runHidden(py, args, l.internalDir, env, logPath)
}

// pipEnvironment is the caller's environment without PYTHON* variables (PYTHONPATH,
// PYTHONSTARTUP, PYTHONHOME… could run code inside pip), plus fixed pip settings. PIP_*
// variables stay: corporate mirrors and proxies are set that way, and hash pinning makes them safe.
func pipEnvironment() []string {
	var env []string
	for _, kv := range os.Environ() {
		name := strings.ToUpper(kv)
		if i := strings.IndexByte(name, '='); i > 0 {
			name = name[:i]
		}
		if strings.HasPrefix(name, "PYTHON") {
			continue
		}
		env = append(env, kv)
	}
	return append(env, "PIP_NO_INPUT=1", "PIP_DISABLE_PIP_VERSION_CHECK=1", "PYTHONNOUSERSITE=1")
}

// installOptional installs optional feature packages. Failure only disables those features
// (for example SNMP shows "component missing"); NodeWatch itself still starts.
func (l *launcher) installOptional(py, optReq, optHash, marker, reqHash string) {
	// After a failure, retry at most every 12 hours so an offline PC is not slowed on every start.
	attempt := marker + ".optional-attempt"
	if st, err := os.Stat(attempt); err == nil && time.Since(st.ModTime()) < 12*time.Hour {
		l.logf("optional components not installed; next attempt after %s", st.ModTime().Add(12*time.Hour).Format(time.RFC3339))
		return
	}
	pinned := filepath.Base(optReq) == optionalLockName
	l.logf("installing optional components from %s (hash-verified: %t)", filepath.Base(optReq), pinned)
	if err := l.pipInstall(py, optReq, pinned); err != nil {
		_ = os.WriteFile(attempt, []byte(time.Now().Format(time.RFC3339)+"\n"), 0600)
		l.logf("WARNING: optional components could not be installed (%v); NodeWatch starts without them and retries in 12 hours", err)
		return
	}
	_ = os.Remove(attempt)
	if err := os.WriteFile(marker, []byte(reqHash+"\noptional:"+optHash+"\n"), 0600); err != nil {
		l.logf("could not record optional components: %v", err)
	}
}

func verifyRuntime(py string) error {
	return verifyRuntimeEnv(py, nil, "")
}

